/**
 * Which member profiles we ask search engines to index (LAB-3096).
 *
 * A profile with no bio and no photo is an empty page: a name and nothing else. Those stay reachable, but leave the
 * sitemap, and the frontend marks them `noindex, follow`. On prod (2026-11-09) that is 339 of 3,273 members, and only
 * one of them had any Search Console impressions.
 *
 * The frontend has the same rule in `utils/member-indexing.ts`; change one, change the other.
 */

import { Prisma } from '@prisma/client';
import { directoryListedMemberWhere } from './member-visibility';

/**
 * The members the public member list shows a logged-out visitor: approved, and verified. `GET /v1/members` gets
 * `isVerified=true` from `IsVerifiedMemberInterceptor` unless the caller asks otherwise, so unverified members are
 * not in the listing, `/members/browse` or the sitemap before LAB-3096. The crawl index starts from the same set.
 */
export function memberCrawlIndexWhere(): Prisma.MemberWhereInput {
  return { AND: [directoryListedMemberWhere(), { isVerified: true }] };
}

/** The notices an AI-written bio ends with. They are not the member's bio, so they don't count as text. */
const AI_BIO_NOTICE = /Bio is (?:AI generated|generated by Husky AI)[^.]*\.?/gi;

const NAMED_ENTITIES: Record<string, string> = { nbsp: ' ', amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };

/** The bio's readable text: tags, entities and AI notices removed, whitespace collapsed. */
export function memberBioText(bio: string | null | undefined): string {
  if (!bio) return '';
  return bio
    .replace(/<[^>]*>/g, ' ')
    .replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (entity, code: string) => {
      if (code[0] !== '#') return NAMED_ENTITIES[code.toLowerCase()] ?? entity;
      const value = code[1] === 'x' || code[1] === 'X' ? parseInt(code.slice(2), 16) : parseInt(code.slice(1), 10);
      return Number.isFinite(value) ? String.fromCodePoint(value) : entity;
    })
    .replace(AI_BIO_NOTICE, ' ')
    .replace(/[\s ]+/g, ' ')
    .trim();
}

/** Whether a member's profile has anything beyond a name: a photo, or bio text of any length. */
export function isMemberIndexable(member: {
  imageUid: string | null | undefined;
  bio: string | null | undefined;
}): boolean {
  return !!member.imageUid || memberBioText(member.bio).length > 0;
}

/** The crawl index response: one `{ uid, updatedAt }` per indexable member, in the order given. */
export function toMemberCrawlIndex(
  rows: { uid: string; updatedAt: Date; imageUid: string | null; bio: string | null }[]
) {
  return {
    members: rows.filter(isMemberIndexable).map((row) => ({ uid: row.uid, updatedAt: row.updatedAt.toISOString() })),
  };
}
