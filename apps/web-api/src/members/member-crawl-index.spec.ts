import { isMemberIndexable, memberBioText, memberCrawlIndexWhere, toMemberCrawlIndex } from './member-crawl-index';
import { directoryListedMemberWhere } from './member-visibility';

describe('memberCrawlIndexWhere', () => {
  // The public list gets isVerified=true from IsVerifiedMemberInterceptor; without it, 442 unverified prod members who
  // were never in the listing or the sitemap would join the sitemap.
  it('starts from the public list: approved and verified members', () => {
    expect(memberCrawlIndexWhere()).toEqual({ AND: [directoryListedMemberWhere(), { isVerified: true }] });
  });
});

describe('memberBioText', () => {
  it('returns the readable text of an HTML bio', () => {
    expect(memberBioText('<p>She leads <strong>infra</strong>&nbsp;at&#160;PL &amp; friends.</p>')).toBe(
      'She leads infra at PL & friends.'
    );
  });

  it('drops both AI bio notices', () => {
    expect(memberBioText('<p>Builds things.</p><p><em>Bio is AI generated &amp; may not be accurate.</em></p>')).toBe(
      'Builds things.'
    );
    expect(
      memberBioText(
        '<p>Builds things.</p>\n<p>&nbsp;</p>\n<p><em>Bio is generated by Husky AI & may not be accurate or up to date.</em></p>'
      )
    ).toBe('Builds things.');
  });

  it('treats empty markup and a notice alone as no text', () => {
    expect(memberBioText(null)).toBe('');
    expect(memberBioText(undefined)).toBe('');
    expect(memberBioText('<p><br></p>')).toBe('');
    expect(memberBioText('<p>&nbsp;</p>')).toBe('');
    expect(memberBioText('<p><em>Bio is AI generated &amp; may not be accurate.</em></p>')).toBe('');
  });
});

describe('isMemberIndexable', () => {
  it('indexes a member with a photo, a bio, or both', () => {
    expect(isMemberIndexable({ imageUid: 'img', bio: null })).toBe(true);
    expect(isMemberIndexable({ imageUid: null, bio: '<p>Short.</p>' })).toBe(true);
    expect(isMemberIndexable({ imageUid: 'img', bio: '<p>Short.</p>' })).toBe(true);
  });

  it('does not index a member with neither', () => {
    expect(isMemberIndexable({ imageUid: null, bio: null })).toBe(false);
    expect(isMemberIndexable({ imageUid: '', bio: '<p>&nbsp;</p>' })).toBe(false);
    expect(
      isMemberIndexable({ imageUid: null, bio: '<p><em>Bio is generated by Husky AI & may not be accurate.</em></p>' })
    ).toBe(false);
  });
});

describe('toMemberCrawlIndex', () => {
  it('keeps indexable members, in order, as uid and ISO updatedAt', () => {
    expect(
      toMemberCrawlIndex([
        { uid: 'b', updatedAt: new Date('2026-11-02T10:00:00.000Z'), imageUid: 'img', bio: null },
        { uid: 'empty', updatedAt: new Date('2026-06-01T00:00:00.000Z'), imageUid: null, bio: '<p></p>' },
        { uid: 'a', updatedAt: new Date('2026-01-01T00:00:00.000Z'), imageUid: null, bio: '<p>Hi.</p>' },
      ])
    ).toEqual({
      members: [
        { uid: 'b', updatedAt: '2026-11-02T10:00:00.000Z' },
        { uid: 'a', updatedAt: '2026-01-01T00:00:00.000Z' },
      ],
    });
  });

  it('returns an empty list for no rows', () => {
    expect(toMemberCrawlIndex([])).toEqual({ members: [] });
  });
});
